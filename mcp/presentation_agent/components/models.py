class GenerateSlideResponse(BaseModel):
    """Aggregated result of the slide generation workflow."""

    insight: InsightGenerationResponse = Field(
        ..., description="Outputs from the insight generation stage."
    )
    layout: LayoutSpecification = Field(
        ..., description="Chosen layout specification for the slide."
    )
    draft: SlideDraftResponse = Field(
        ..., description="Final slide draft (copy + PPT metadata)."
    )
    qa_reports: List[SlideQAReport] = Field(
        default_factory=list, description="Ordered QA iteration reports."
    )
    render_artifact: Optional[SlideArtifact] = Field(
        default=None,
        description="Metadata for the rendered slide image artifact.",
    )


class PresentationAssemblyRequest(BaseModel):
    """Bundle slides into a deliverable artifact."""
    title: Optional[str] = Field(
        default=None,
        description="Optional presentation title",
    )
    thread_id: str = Field(
        default=None,
        description="Upstream conversation thread identifier for logging/artifacts.",
    )


class PresentationAssemblyResponse(BaseModel):
    """Minimal artifact handle for the assembled presentation."""

    artifact_path: str = Field(
        ...,
        description="URI or relative path where the assembled deck lives.",
    )
    preview_snippet: Optional[str] = Field(
        default=None,
        description="Short preview of the final artifact (e.g., link or excerpt).",
    )
    slide_count: Optional[int] = Field(
        default=None, description="Number of slides bundled into the artifact."
    )


class DataAsset(BaseModel):
    """Reference to a dataset or artifact that the sandbox can ingest."""

    name: str = Field(..., description="Human friendly name for the asset.")
    path: str = Field(..., description="Absolute path or s3:// URI to the asset.")
    description: Optional[str] = Field(
        default=None, description="Context that should influence the analysis."
    )
    size: Optional[int] = Field(
        default=None, description="Optional size metadata to seed the CEL log."
    )
    version_id: Optional[str] = Field(
        default=None,
        description="Optional object version for deterministic downloads.",
    )


class InsightGenerationRequest(BaseModel):
    """
    Inputs for statistical/visual storytelling aimed at slide-ready outputs.
    """
    task: str = Field(..., description="High-level goal for the statistical insight.")
    data_assets: List[DataAsset] = Field(
        default_factory=list,
        description="Datasets or tables to analyse. Supply s3:// URIs when remote.",
    )
    research_context: List[DataAsset] = Field(
        default_factory=list,
        description="Narrative or research context to seed the analysis. Supply s3:// URIs.",
    )


class InsightGenerationResponse(BaseModel):
    """Outputs from a statistical insight run."""

    ok: bool
    summary: str = Field(
        ..., description="LLM-evaluated summary tailored for slide narratives."
    )
    stdout: str = Field(default="", description="Raw stdout from the sandbox run.")
    stderr: str = Field(default="", description="Raw stderr from the sandbox run.")
    artifacts: List[dict] = Field(
        default_factory=list,
        description="Artifacts captured from outputs/ (charts, tables, notes).",
    )
    code_reference: Optional[str] = Field(
        default=None,
        description="Path or URI for the executed Python cell for auditing.",
    )


class OutlineArtifact(BaseModel):
    """Narrative or research artifact to guide outline planning."""

    name: str = Field(..., description="Artifact identifier (e.g., narrative.md).")
    path: Optional[str] = Field(
        default=None, description="Optional path/URI so the planner can reference provenance."
    )
    summary: Optional[str] = Field(
        default=None,
        description="Short summary of the artifact's content.",
    )
    content: Optional[str] = Field(
        default=None,
        description="Inline text excerpt to seed the planner (truncated upstream if large).",
    )


class PresentationWorkflowRequest(BaseModel):
    """End-to-end presentation workflow input."""

    thread_id: str = Field(..., description="Shared sandbox session identifier.")
    topic: str = Field(..., description="Presentation topic or narrative brief.")
    audience: str = Field(
        default="general",
        description="Intended audience persona (e.g., executives, engineers).",
    )
    desired_outcome: Optional[str] = Field(
        default=None,
        description="Desired impact or call to action for the audience.",
    )
    research_context: Optional[str] = Field(
        default=None,
        description="Qualitative findings to seed insights and slide copy.",
    )
    slide_count_hint: Optional[int] = Field(
        default=None,
        ge=1,
        description="Optional target number of slides to influence planning.",
    )
    include_appendix: bool = Field(
        default=False,
        description="Reserve appendix space when True.",
    )
    data_assets: List[DataAsset] = Field(
        default_factory=list,
        description="Structured datasets to analyse (S3 paths preferred).",
    )
    outline_artifacts: List[OutlineArtifact] = Field(
        default_factory=list,
        description="Narrative artifacts to seed outline planning.",
    )
    max_iterations: Optional[int] = Field(
        default=1,
        description="Maximum LangGraph passes through evidence/drafting loop.",
    )


class PresentationWorkflowResponse(BaseModel):
    """Aggregated output of the presentation workflow."""

    thread_id: str
    outline: PresentationOutlineResponse
    slide_drafts: Dict[str, SlideDraftResponse]
    deck: Optional[PresentationAssemblyResponse] = None
    insights: Dict[str, dict] = Field(default_factory=dict)


PresentationOutlineRequest.model_rebuild()
